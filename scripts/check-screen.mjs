function setup(system) {
  document.activeElement = createElement('body');
  const desktop = createScreen(system), root = createDesktopControls(), events = new AbortController(), messages = [];
  root.hidden = false;
  desktop.bindControls(root, message => messages.push(message), events.signal);
  const surface = desktop.texture.image;
  let now = start;
  const update = (time = now) => { now = time; system?.update(time); desktop.update(time); };
  update();
  const control = id => root.querySelector(`[data-control="${id}"]`);
  const uv = (x, y) => ({ x: x / surface.width, y: 1 - y / surface.height });
  function point(id) {
    assert.ok(control(id) && !control(id).hidden, `Visible native control ${id}`);
    for (let y = 3; y < 675; y += 6) for (let x = 3; x < 1200; x += 6) if (desktop.hitTest(uv(x, y)) === id) return uv(x, y);
    assert.fail(`Control ${id} must be reachable through the public UV interface`);
  }
  function click(id) { const value = point(id); assert.equal(desktop.handleInput({ type: 'pointerdown' }, value), true); assert.equal(desktop.handleInput({ type: 'pointerup' }, value), true); update(); }
  return { desktop, root, surface, messages, control, uv, point, click, update, dispose() { events.abort(); desktop.dispose(); desktop.texture.dispose(); } };
}
