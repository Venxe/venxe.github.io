import assert from 'node:assert/strict';
import { createSystem } from '../src/system.js';

let now = 0;
Date.now = () => now;
const system = createSystem();
const advance = (ms) => { now += ms; system.update(now); };
assert.equal(system.state.phase, 'desktop');
system.send('shutdown');
assert.equal(system.state.phase, 'shutting-down');
advance(1399);
assert.equal(system.state.phase, 'shutting-down');
advance(1);
assert.equal(system.state.phase, 'off');
assert.equal(system.state.brightness, 0);
system.send('lid', true);
system.send('lid', false);
assert.equal(system.state.phase, 'off', 'Opening the lid cannot power on the computer');
system.send('press');
system.send('release');
assert.equal(system.state.phase, 'booting');
advance(9284);
assert.equal(system.state.phase, 'login');
system.send('restart');
advance(1400);
assert.equal(system.state.phase, 'off');
assert.equal(system.state.restarting, true);
advance(599);
assert.equal(system.state.phase, 'off');
advance(1);
assert.equal(system.state.phase, 'booting');
advance(9284);
assert.equal(system.state.phase, 'login');
system.send('press');
advance(1999);
assert.equal(system.state.phase, 'login');
system.send('cancel-press');
advance(10);
assert.equal(system.state.phase, 'login');
system.send('press');
advance(2000);
assert.equal(system.state.phase, 'off');
system.send('release');
assert.equal(system.state.phase, 'off', 'Releasing a forced shutdown must not reboot');
system.dispose();
system.send('press');
system.send('release');
assert.equal(system.state.phase, 'off');
console.log('PASS: initial session, shutdown, restart, cold boot, lid, power hold/cancellation, and disposal.');

const session = createSystem();
session.send('logout');
assert.equal(session.state.phase, 'signing-out');
now += 350;
session.update();
assert.equal(session.state.phase, 'login');
await session.send('login', 'incorrect-test-input');
assert.match(session.state.error, /Incorrect/);
assert.equal(session.state.phase, 'login');

// Only the browser's crypto boundary is replaced. Never put the real credential in fixtures.
const digest = crypto.subtle.digest;
const acceptedDigest = Uint8Array.from(Buffer.from('8cd6cb7e1601eb5dcd0a0d3d8f62c2dd8ee483819f9130a34259a217e927679f', 'hex'));
crypto.subtle.digest = async () => acceptedDigest.buffer;
await session.send('login', 'fixture');
assert.equal(session.state.phase, 'signing-in');
session.send('lid', true);
now += 350;
session.update();
assert.equal(session.state.phase, 'login', 'Closing the lid during sign-in must prevent desktop entry');
session.send('lid', false);
await session.send('login', 'fixture');
now += 350;
session.update();
assert.equal(session.state.phase, 'desktop');
session.send('lid', true);
assert.equal(session.state.phase, 'login');
assert.equal(session.state.closed, true);
await session.send('login', 'fixture');
assert.equal(session.state.phase, 'login', 'Closed lid must block sign in');
session.send('lid', false);
let resolveDigest;
crypto.subtle.digest = () => new Promise((resolve) => { resolveDigest = resolve; });
const attempt = session.send('login', 'fixture');
assert.equal(session.state.verifying, true);
session.send('shutdown');
resolveDigest(acceptedDigest.buffer);
await attempt;
assert.equal(session.state.phase, 'shutting-down', 'Stale verification must not reopen the desktop');
now += 1400;
session.update();
session.send('press');
session.send('release');
now += 9284;
session.update();
crypto.subtle.digest = async () => { throw new Error('Unavailable'); };
await session.send('login', 'fixture');
assert.match(session.state.error, /unavailable/);
crypto.subtle.digest = digest;
session.dispose();
console.log('PASS: logout, masked credential verification boundary, lock, stale async result, and crypto failure.');

const reduced = createSystem();
reduced.update(now, true);
reduced.send('shutdown');
now += 400;
reduced.update();
assert.equal(reduced.state.phase, 'off');
reduced.send('press');
reduced.send('release');
reduced.send('lid', true);
now += 5050;
reduced.update();
assert.equal(reduced.state.phase, 'login', 'Boot must finish while the lid is closed');
reduced.send('lid', false);
assert.equal(reduced.state.phase, 'login');
reduced.send('press');
now += 1999;
reduced.update();
assert.equal(reduced.state.phase, 'login', 'Reduced motion must preserve the hold threshold');
now++;
reduced.update();
assert.equal(reduced.state.phase, 'off');
reduced.dispose();
console.log('PASS: reduced-motion transitions, boot behind a closed lid, and unchanged hold duration.');
