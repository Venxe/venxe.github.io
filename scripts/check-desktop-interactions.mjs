import assert from 'node:assert/strict';
import { VIEWPORTS, setup, send, wallTime, setWallTime } from './test-interactions.mjs';

export async function runDesktopInteractions() {
  for (const [width, height] of VIEWPORTS) {
    const test = setup(width, height);
    const root = test.elements.get('desktop-controls');
    const control = id => root.querySelector(`[data-control="${id}"]`);
    test.key('Enter'); test.tick();
    assert.equal(root.hidden, false);
    test.click(30 / 1200, 1 - 450 / 675); test.tick();
    assert.equal(control('dashboard').getAttribute('aria-expanded'), 'true', 'UV input must open Dashboard');
    assert.ok(test.screen.material.map.image.labels.some(label => label.text === 'October 2026'));
    const version = test.screen.material.map.version;
    test.resize(height, width); test.tick();
    assert.equal(test.screen.material.map.version, version, 'Viewport resize does not rebuild the desktop');
    test.resize(width, height); test.tick(); test.key('Escape'); test.tick();
    assert.equal(test.mode, 'laptop', 'Escape closes a drawer before changing view');
    test.click(1168 / 1200, 1 - 638 / 675); test.tick();
    assert.equal(control('utilities').getAttribute('aria-expanded'), 'true');
    const [x, y] = test.screenPoint(1000 / 1200, 1 - 450 / 675);
    const position = test.camera.position.clone();
    const wheel = send(test.canvas, 'wheel', { deltaY: 120, deltaMode: 0, timeStamp: wallTime, clientX: x, clientY: y }); test.tick();
    assert.equal(wheel.defaultPrevented, true);
    assert.ok(test.camera.position.distanceTo(position) < 1e-8);
    test.pointer('pointerdown', x, y, 1, 'touch'); test.pointer('pointermove', x, y - 30, 1, 'touch'); test.pointer('pointerup', x, y - 30, 1, 'touch'); test.tick();
    assert.ok(test.camera.position.distanceTo(position) < 1e-8, 'Panel drags must not move the camera');
    test.key('Escape'); control('launcher').click(); test.tick();
    control('search').focus(); control('search').value = 'terminal'; send(control('search'), 'input'); test.tick();
    const beforeTyping = test.camera.position.clone();
    send(test.document, 'keydown', { key: '-', code: 'Minus' }); test.tick();
    assert.ok(test.camera.position.distanceTo(beforeTyping) < 1e-8, 'Search typing must not zoom');
    control('app-terminal').click(); test.tick();
    assert.ok(test.screen.material.map.image.labels.some(label => label.text === 'foot — venxe@venxe-laptop'));
    test.key('Escape'); test.tick(); test.key('Enter'); test.tick();
    test.pinch(5); test.tick();
    assert.equal(test.mode, 'screen');
    control('dashboard').click(); test.tick(); assert.equal(control('dashboard').getAttribute('aria-expanded'), 'true');
    test.key('Escape'); test.tick(); assert.equal(test.mode, 'screen');
    test.document.hidden = true; send(test.document, 'visibilitychange'); assert.equal(root.hidden, true);
    setWallTime(new Date(2026, 9, 14, 0, 0).getTime()); test.document.hidden = false; send(test.document, 'visibilitychange'); test.tick();
    assert.match(control('dashboard').getAttribute('aria-label'), /00:00/);
    send(test.canvas, 'webglcontextlost'); assert.equal(root.hidden, true); test.close();
  }
  console.log('PASS: Caelestia UV input across viewports, drawer Escape priority, wheel/touch isolation, search input, fullscreen, tab-resume clock and context loss.');

  const powerFlow = setup(1440, 900, false);
  powerFlow.key('Enter');
  powerFlow.tick(20);
  const powerRoot = powerFlow.elements.get('desktop-controls');
  const powerControl = (id) => powerRoot.querySelector(`[data-control="${id}"]`);
  const powerAction = (id) => {
    powerControl('session').click();
    powerControl(id).click();
  };
  const powerLed = powerFlow.workspace.getObjectByName('power-light');
  const systemGlow = powerFlow.screen.children.find((object) => object.isPointLight);
  powerAction('logout');
  powerFlow.tick(8);
  assert.equal((powerControl('password')?.hidden ?? true), true);
  assert.equal(powerControl('unlock').hidden, false);
  const cameraBeforeReveal = powerFlow.camera.position.clone();
  assert.equal(powerFlow.key('+').defaultPrevented, true);
  powerFlow.tick(10);
  assert.ok(powerFlow.camera.position.distanceTo(cameraBeforeReveal) < 1e-8, 'The wake key must not zoom the camera');
  assert.equal((powerControl('password')?.hidden ?? true), false);
  assert.equal(powerFlow.document.activeElement, powerControl('password'));
  assert.equal(powerControl('password').value, '', 'The first key must only reveal the form');
  assert.equal(powerControl('dashboard').hidden, true);
  const digestBoundary = crypto.subtle.digest;
  crypto.subtle.digest = async () => Uint8Array.from(Buffer.from('8cd6cb7e1601eb5dcd0a0d3d8f62c2dd8ee483819f9130a34259a217e927679f', 'hex')).buffer;
  powerControl('password').value = 'fixture';
  send(powerControl('password'), 'keydown', { key: 'Enter' });
  await new Promise((resolve) => setTimeout(resolve, 0));
  crypto.subtle.digest = digestBoundary;
  powerFlow.tick(8);
  assert.equal(powerControl('dashboard').hidden, false, 'Submitting the native password field must restore the desktop');
  powerAction('shutdown');
  powerFlow.tick(10);
  assert.ok(powerFlow.screen.material.map.image.labels.some(({ text }) => text === 'Shutting down…'));
  powerFlow.tick(18);
  assert.equal(powerFlow.screen.material.color.r, 0);
  assert.equal(systemGlow.intensity, 0);
  assert.equal(powerLed.visible, false);
  assert.equal(powerRoot.hidden, true);
  let [powerX, powerY] = powerFlow.projectPoint(powerLed);
  powerFlow.pointer('pointerdown', powerX, powerY);
  powerFlow.pointer('pointerup', powerX, powerY);
  powerFlow.tick(9);
  assert.ok(powerFlow.screen.material.map.image.labels.some(({ text }) => text === 'CachyOS'));
  assert.equal(powerControl('boot-normal').hidden, false);
  const bootCamera = powerFlow.camera.position.clone();
  powerFlow.key('ArrowDown');
  powerFlow.tick();
  assert.equal(powerControl('boot-lts').getAttribute('aria-pressed'), 'true');
  assert.ok(powerFlow.camera.position.distanceTo(bootCamera) < 1e-8, 'Menu arrows must not move the camera');
  powerFlow.tick(70);
  assert.equal(powerControl('boot-normal').hidden, false, 'Interacting with Limine must stop autoboot');
  powerFlow.keyDown('Enter', true);
  powerFlow.tick();
  assert.equal(powerControl('boot-normal').hidden, false, 'Repeated Enter must not start the selected entry');
  powerFlow.key('Enter');
  powerFlow.tick(6);
  assert.ok(powerFlow.screen.material.map.image.labels.some(({ text }) => text.includes('initramfs-linux-cachyos-lts.img')));
  assert.equal(powerControl('boot-normal').hidden, true);
  powerFlow.tick(115);
  assert.equal(powerControl('unlock').hidden, false);
  assert.equal((powerControl('password')?.hidden ?? true), true);
  const [unlockX, unlockY] = powerFlow.screenPoint(0.5, 0.5);
  powerFlow.pointer('pointerdown', unlockX, unlockY, 1, 'touch');
  powerFlow.pointer('pointerup', unlockX, unlockY, 1, 'touch');
  powerFlow.tick(10);
  assert.equal((powerControl('password')?.hidden ?? true), false, 'A screen tap must reveal the login form');
  assert.equal(powerLed.visible, true);

  for (const cancellation of ['pointercancel', 'lostpointercapture', 'pointerleave']) {
    [powerX, powerY] = powerFlow.projectPoint(powerLed);
    powerFlow.pointer('pointerdown', powerX, powerY);
    powerFlow.tick(10);
    powerFlow.pointer(cancellation, powerX, powerY);
    powerFlow.tick(40);
    powerFlow.pointer('pointerup', powerX, powerY);
    assert.equal(powerFlow.screen.material.color.r, 1, 'Cancelled holds must not power off');
  }
  [powerX, powerY] = powerFlow.projectPoint(powerLed);
  const cameraBeforePower = powerFlow.camera.position.clone();
  powerFlow.pointer('pointerdown', powerX, powerY);
  powerFlow.pointer('pointermove', powerX + 30, powerY);
  powerFlow.tick(45);
  powerFlow.pointer('pointerup', powerX + 30, powerY);
  assert.equal(powerFlow.screen.material.color.r, 1, 'Dragging away must cancel the power hold');
  assert.ok(powerFlow.camera.position.distanceTo(cameraBeforePower) < 1e-8, 'Power gestures must not orbit the camera');
  [powerX, powerY] = powerFlow.projectPoint(powerLed);
  powerFlow.pointer('pointerdown', powerX, powerY, 1, 'touch');
  powerFlow.pointer('pointerdown', powerX + 20, powerY, 2, 'touch');
  powerFlow.tick(45);
  powerFlow.pointer('pointerup', powerX, powerY, 1, 'touch');
  powerFlow.pointer('pointerup', powerX + 20, powerY, 2, 'touch');
  assert.equal(powerFlow.screen.material.color.r, 1, 'A second finger must cancel the power hold');

  [powerX, powerY] = powerFlow.projectPoint(powerLed);
  const capturedPower = powerFlow.pointer('pointerdown', powerX, powerY);
  assert.equal(capturedPower.defaultPrevented, true, 'Physical power input must be captured before camera input');
  powerFlow.tick(39);
  assert.equal(powerFlow.screen.material.color.r, 1);
  powerFlow.tick();
  assert.equal(powerFlow.screen.material.color.r, 0, 'Two seconds must force power off');
  powerFlow.pointer('pointerup', powerX, powerY);
  powerFlow.tick(5);
  assert.equal(powerFlow.screen.material.color.r, 0, 'Releasing must not restart after a forced shutdown');
  const hardwarePowerButton = powerFlow.elements.get('laptop-power');
  send(hardwarePowerButton, 'click', { detail: 0 });
  powerFlow.tick(186);
  assert.equal(powerControl('unlock').hidden, false, 'Assistive click must start a powered-off laptop at the SDDM welcome');
  send(hardwarePowerButton, 'keydown', { key: 'Enter' });
  powerFlow.tick(40);
  send(hardwarePowerButton, 'keyup', { key: 'Enter' });
  send(hardwarePowerButton, 'click', { detail: 0 });
  powerFlow.tick();
  assert.equal(powerFlow.screen.material.color.r, 0, 'A synthesized click after key release must not reboot');
  send(powerFlow.elements.get('laptop-lid-toggle'), 'click');
  powerFlow.tick(14);
  send(powerFlow.elements.get('laptop-lid-toggle'), 'click');
  powerFlow.tick(30);
  assert.equal(powerFlow.screen.material.color.r, 0, 'Reopening a powered-off laptop must leave its screen black');
  assert.equal(systemGlow.intensity, 0);
  powerFlow.close();
  console.log('PASS: complete native login and power cycles, physical power picking, LED/glow, cancelled/drag/multi-touch holds, assistive power input, and off-state lid reopening.');

  for (const cancellation of ['wheel', 'blur', 'visibility', 'view', 'lid']) {
    const interrupted = setup(1440, 900);
    interrupted.key('Enter');
    const button = interrupted.elements.get('laptop-power');
    const keys = interrupted.workspace.getObjectByName('keyboard');
    const resting = keys.instanceMatrix.array.slice();
    send(button, 'keydown', { key: 'Enter' });
    interrupted.tick(10);
    assert.notDeepEqual(keys.instanceMatrix.array, resting, 'The native power hold must depress the physical key');
    if (cancellation === 'wheel') interrupted.wheel(120);
    else if (cancellation === 'blur') send(interrupted.window, 'blur');
    else if (cancellation === 'visibility') {
      interrupted.document.hidden = true;
      send(interrupted.document, 'visibilitychange');
      setWallTime(wallTime + 2500);
      interrupted.document.hidden = false;
      send(interrupted.document, 'visibilitychange');
    } else if (cancellation === 'view') interrupted.key('Escape');
    else send(interrupted.elements.get('laptop-lid-toggle'), 'click');
    interrupted.tick(45);
    send(button, 'keyup', { key: 'Enter' });
    assert.equal(interrupted.workspace.getObjectByName('power-light').visible, true, `${cancellation} must cancel a hold before forced shutdown`);
    assert.deepEqual(keys.instanceMatrix.array, resting, `${cancellation} must release the physical power key`);
    interrupted.close();
  }

  const cleanup = setup(1440, 900);
  const cleanupButton = cleanup.elements.get('laptop-power');
  const cleanupKeys = cleanup.workspace.getObjectByName('keyboard');
  const resting = cleanupKeys.instanceMatrix.array.slice();
  send(cleanupButton, 'keydown', { key: 'Enter' });
  cleanup.tick(10);
  cleanup.close();
  assert.deepEqual(cleanupKeys.instanceMatrix.array, resting, 'Page disposal must cancel and release an active power hold');
  const announcement = cleanup.elements.get('announcement').textContent;
  assert.equal(send(cleanupButton, 'keydown', { key: 'Enter' }).defaultPrevented, false, 'Page disposal must remove native power listeners');
  send(cleanupButton, 'pointerdown', { button: 0, pointerId: 1 });
  cleanup.pointer('pointerdown', 720, 450);
  assert.equal(cleanup.elements.get('announcement').textContent, announcement, 'Disposed power listeners must not announce new gestures');
  console.log('PASS: power capture priority, wheel/blur/visibility/view/lid hold cancellation, key release, and listener cleanup.');

  for (const [width, height] of [[1440, 900], [390, 844]]) {
    const boot = setup(width, height);
    boot.key('Enter');
    const root = boot.elements.get('desktop-controls');
    const control = (id) => root.querySelector(`[data-control="${id}"]`);
    for (const id of ['session', 'restart']) control(id).click();
    boot.tick(24);
    assert.equal(control('boot-normal').hidden, false, 'Restart must expose Limine in the laptop view');
    const beforeWheel = boot.camera.position.clone();
    const [x, y] = boot.screenPoint(0.45, 1 - 348 / 675);
    const wheel = send(boot.canvas, 'wheel', { clientX: x, clientY: y, deltaY: 100, timeStamp: wallTime });
    assert.equal(wheel.defaultPrevented, true);
    boot.tick();
    assert.equal(control('boot-lts').getAttribute('aria-pressed'), 'true');
    assert.ok(boot.camera.position.distanceTo(beforeWheel) < 1e-8, 'Wheeling over Limine must select without zooming');
    boot.key('Escape');
    assert.equal(boot.mode, 'free', 'Escape in Limine must return to the scene');
    boot.tick(80);
    assert.equal(control('boot-normal').hidden, false, 'Returning to the scene must not resume a stopped countdown');
    boot.key('Enter');
    assert.equal(boot.mode, 'laptop');
    assert.equal(root.hidden, false);
    const [tapX, tapY] = boot.screenPoint(0.45, 1 - 348 / 675);
    boot.pointer('pointerdown', tapX, tapY, 1, 'touch');
    boot.pointer('pointerdown', tapX + 20, tapY, 2, 'touch');
    boot.pointer('pointerup', tapX, tapY, 1, 'touch');
    boot.pointer('pointerup', tapX + 20, tapY, 2, 'touch');
    boot.tick();
    assert.equal(control('boot-normal').hidden, false, 'A second touch must cancel the boot tap');
    const [confirmX, confirmY] = boot.screenPoint(0.45, 1 - 348 / 675);
    boot.pointer('pointerdown', confirmX, confirmY, 1, 'touch');
    boot.pointer('pointerup', confirmX, confirmY, 1, 'touch');
    boot.tick(6);
    assert.equal(control('boot-normal').hidden, true);
    assert.ok(boot.screen.material.map.image.labels.some(({ text }) => text.includes('initramfs-linux-cachyos-lts.img')));
    boot.tick(30);
    assert.equal(control('unlock').hidden, false);
    boot.close();
  }
  console.log('PASS: desktop/mobile Limine wheel isolation, Escape scene return, stopped timers and single/multiple-touch boot gestures.');

  for (const bootElapsed of [0, 8500]) {
    const hold = setup(1440, 900, false);
    hold.key('Enter');
    hold.tick(20);
    const root = hold.elements.get('desktop-controls');
    for (const id of ['session', 'restart']) root.querySelector(`[data-control="${id}"]`).click();
    hold.tick(40 + bootElapsed / 50);
    const button = hold.elements.get('laptop-power');
    button.focus();
    send(button, 'keydown', { key: 'Enter' });
    hold.tick(40);
    assert.equal(hold.workspace.getObjectByName('power-light').visible, false, 'Automatic menu/login focus must not cancel an active native power hold');
    send(button, 'keyup', { key: 'Enter' });
    hold.close();
  }
  console.log('PASS: native power holds survive automatic boot menu and login transitions.');
}
