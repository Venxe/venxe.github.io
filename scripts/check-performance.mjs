import assert from 'node:assert/strict';
import { setup, send, THREE } from './test-interactions.mjs';

const test = setup(1440, 900, true);
test.tick(20);
const renders = test.renderer.renderCalls;
test.tick(20);
assert.equal(test.renderer.renderCalls, renders, 'A settled reduced-motion scene does no GPU work');
assert.equal(test.pendingFrames, 0, 'A settled scene has no continuous animation callback');
assert.equal(test.pendingTimers, 1, 'Only the next clock deadline is scheduled');
test.key('Enter'); test.tick(20);
test.key('+'); test.tick(20);
assert.equal(test.mode, 'screen');
const screenRenders = test.renderer.renderCalls;
test.tick(20);
assert.equal(test.renderer.renderCalls, screenRenders, 'An unchanged screen is not rendered again');
test.elements.get('desktop-controls').querySelector('[data-control="dashboard"]').click(); test.tick();
assert.ok(test.renderer.renderCalls > screenRenders, 'Native desktop input wakes a sleeping renderer');
test.document.hidden = true; send(test.document, 'visibilitychange');
assert.equal(test.pendingFrames, 0); assert.equal(test.pendingTimers, 0);
test.document.hidden = false; send(test.document, 'visibilitychange'); test.tick();
test.close();
assert.equal(test.pendingFrames, 0); assert.equal(test.pendingTimers, 0);
const hover = setup(1440, 900, true);
hover.key('Enter'); hover.tick(20);
let raycasts = 0;
const intersect = THREE.Raycaster.prototype.intersectObjects;
THREE.Raycaster.prototype.intersectObjects = function(...args) { raycasts++; return intersect.apply(this, args); };
for (let i = 0; i < 10; i++) hover.pointer('pointermove', 720 + i, 450);
hover.tick();
assert.equal(raycasts, 1, 'Desktop hover and physical cursor selection share the event raycast');
THREE.Raycaster.prototype.intersectObjects = intersect;
hover.close();
const wake = setup(390, 844, true);
wake.key('Enter'); wake.tick(20); wake.key('+'); wake.tick(20);
const root = wake.elements.get('desktop-controls');
const control = id => root.querySelector(`[data-control="${id}"]`);
control('utilities').click(); wake.tick();
control('volume').value = '37'; send(control('volume'), 'input'); wake.tick();
assert.equal(control('volume').getAttribute('aria-valuetext'), '37%');
wake.key('Escape'); wake.tick();
assert.ok(wake.screen.material.map.image.labels.some(label => label.text === '37'), 'The OSD displays the new volume after closing Utilities');
wake.tick(40);
assert.equal(wake.pendingFrames, 0, 'The expired OSD returns to sleep');
const minuteVersion = wake.screen.material.map.version;
wake.tick(1200);
assert.ok(wake.screen.material.map.version > minuteVersion, 'The minute timer refreshes a sleeping desktop');
send(wake.canvas, 'webglcontextlost');
assert.equal(wake.pendingFrames, 0); assert.equal(wake.pendingTimers, 0);
wake.close();
const paused = setup(1440, 900, false);
paused.key('Enter'); paused.tick(4);
paused.document.hidden = true; send(paused.document, 'visibilitychange'); paused.tick(100);
paused.document.hidden = false; send(paused.document, 'visibilitychange'); paused.tick();
const resumedPosition = paused.camera.position.clone();
paused.tick(20);
assert.ok(paused.camera.position.distanceTo(resumedPosition) > 0.1, 'A hidden tab pauses the camera transition instead of finishing it offscreen');
paused.close();
console.log('PASS: idle render budget, native-input wake, single deadline, visibility and disposal cancellation.');
